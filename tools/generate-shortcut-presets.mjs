// Regenerate exact selectable route solutions: node tools/generate-shortcut-presets.mjs
// Optional expensive freshness audit: node tools/generate-shortcut-presets.mjs --check
import { readFile, writeFile } from 'node:fs/promises';
import { Course } from '../src/course.js';
import { COURSE } from '../src/config.js';
import { ROUTE_VARIANTS, supportsRouteVariants } from '../src/route-variants.js';
import { SHORTCUT_GENERATION_VERSION, shortcutPresetFingerprint } from '../src/shortcut-preset-cache.js';
import { shortcutSourceFingerprint } from './shortcut-preset-freshness.mjs';

const sourceFingerprint=await shortcutSourceFingerprint();
const entries=[];
for(const definition of COURSE){
  if(definition.arena||definition.expansion)continue;
  const seeds=supportsRouteVariants(definition)?ROUTE_VARIANTS.map(route=>route.seed):[1989];
  for(const seed of seeds){
    const course=new Course(definition,seed,{solveShortcuts:true});
    entries.push({event:definition.id,seed,fingerprint:shortcutPresetFingerprint(course),shortcuts:course.features.shortcuts});
    console.log(`${definition.id}/${seed}: ${course.features.shortcuts.length} exact shortcut paths`);
  }
}
const data={version:SHORTCUT_GENERATION_VERSION,sourceFingerprint,entries};
const text='// Generated by tools/generate-shortcut-presets.mjs. Do not edit by hand.\nexport const SHORTCUT_PRESET_DATA = '+JSON.stringify(data)+';\n';
const target=new URL('../src/generated-shortcut-presets.js',import.meta.url);
if(process.argv.includes('--check')){
  const saved=await readFile(target,'utf8');if(saved!==text)throw new Error('Shortcut presets are stale. Run node tools/generate-shortcut-presets.mjs.');
  console.log(`Shortcut presets are fresh: ${entries.length} layouts, ${Buffer.byteLength(text)} bytes.`);
}else{await writeFile(target,text);console.log(`Saved ${entries.length} exact layouts (${Buffer.byteLength(text)} bytes).`);}
