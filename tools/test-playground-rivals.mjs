import assert from 'node:assert/strict';
import {Duel} from '../src/game.js';
import {App} from '../src/app.js';
import {CARS,BOOST} from '../src/config.js';
import {normalizeRival} from '../src/rival-settings.js';
import {bestKey,upgradedCar,createProfile} from '../src/progression.js';
import {recordFinish,createLeaderboard,saveLeaderboard,loadLeaderboard} from '../src/leaderboard.js';
import {applyDriverModifiers} from '../src/drivers.js';
import {FREESTYLE_DRAG} from '../src/freestyle-course.js';
let checks=0;const check=(v,label)=>{assert.ok(v,label);checks++;};
const memory=new Map();globalThis.localStorage={getItem:k=>memory.get(k)??null,setItem:(k,v)=>memory.set(k,String(v))};
check(normalizeRival({car:'bad',driverId:'bad',upgradeLevel:NaN})===null,'invalid settings return legacy rival');
check(normalizeRival({car:'titan_monster',upgradeLevel:999}).upgradeLevel===3,'upgrade level bounded');
for(const car of ['titan_monster','koenigsegg_jesko']){
  const duel=new Duel();duel.startCampaign({startStage:15,car});
  const s=duel.state;Object.assign(s,{status:'racing',s:0,lateral:FREESTYLE_DRAG.startX,headingError:Math.PI/2});
  duel.setInput({throttle:1,boost:true});let peak=0;
  for(let i=0;i<90*60;i++){
    duel.step(1/60);peak=Math.max(peak,s.speedMph);
    check(s.boost===1,'held boost never drains in practice');
    const p=duel.course.worldAt(s.s,s.lateral);
    if(p.x>=FREESTYLE_DRAG.endX)break;
  }
  const p=duel.course.worldAt(s.s,s.lateral),ceiling=duel.car.topSpeed*(BOOST.topSpeedMult+s.upgrades.nitro*.025+(duel.car.nitroSpeedBonus||0));
  check(p.x>=FREESTYLE_DRAG.endX&&Math.abs(p.z)<.1,'input-only straight drive reaches end without drift');
  check(peak>=ceiling*.99,'strip reaches actual boosted maximum speed');
  check(s.majorCrashes===0&&s.status==='racing'&&!s.results,'no obstacles, finish or reward on runway');
  duel.setInput({throttle:0,boost:false,brake:1});for(let i=0;i<20*60&&s.speedMph>0;i++)duel.step(1/60);
  check(duel.course.worldAt(s.s,s.lateral).x<FREESTYLE_DRAG.runoutEndX,'braking runout stops each car');
  Object.assign(s,{s:0,lateral:20,speedMph:40,gear:1,boost:0});duel.setInput({throttle:1,brake:0,boost:true});duel.step(1/60);
  check(s.boosting&&s.boost===1,'nitro works on unpaved practice ground with empty legacy tank');
  check(duel._drivingSurface(0,-100).boostAllowed,'offroad practice permits boost');
  Object.assign(s,{gear:-1,speedMph:-5});duel.setInput({throttle:0,brake:1,boost:true});duel.step(1/60);check(!s.boosting,'reverse braking does not fire nitro');
  console.log(`${car}: ${Math.round(peak*1.609344)} km/h, clear straight and braking runout.`);
}
const normal=new Duel();normal.startCampaign({car:'falcone_f42'});Object.assign(normal.state,{status:'racing',speedMph:60,gear:2});normal.setInput({boost:true,throttle:1});normal.step(1/60);
check(normal.state.boost<1,'normal race tank still drains');check(!normal._drivingSurface(0,100).boostAllowed,'normal offroad boost restriction unchanged');
const rival={car:'koenigsegg_jesko',driverId:'axel_storm',upgradeLevel:0};
const app=new App();const first=app.player.id;app.setRaceSettings({rival});app.startCampaign();
check(app.duel.state.rival.car===rival.car&&app.duel.state.rival.driverId===rival.driverId,'actual App creates selected rival');
const max=Object.fromEntries(['engine','nitro','handling','tires','brakes','suspension','tank'].map(k=>[k,3]));
check(app.duel.rivalSpec.grip===applyDriverModifiers(upgradedCar(CARS[rival.car],max),rival.driverId,rival.car).grip,'factory-max upgrades and driver skills affect CPU physics');
app.restart();check(app.duel.state.rival.car===rival.car,'restart retains rival');app.returnToMenu();app.addPlayer('Other');check(!app.getRaceChoices().rival,'new account uses default rival');
app.selectPlayer(first);check(app.getRaceChoices().rival.car===rival.car,'switch restores rival');check(new App().getRaceChoices().rival.car===rival.car,'reload restores rival');
check(!app.profile.unlockedCars.includes(rival.car),'opponent selection never grants player ownership');
app.startCampaign({mode:'timetrial'});check(app.duel.state.rival===null,'time trial never spawns chosen rival');
const result={stageIndex:0,seed:1989,laps:2,car:'falcone_f42',mode:'duel',cpuDifficulty:'easy',difficulty:'casual',completed:true,won:true,timeSec:100,upgrades:{}};
check(bestKey(result)!==bestKey({...result,rival}),'custom rival car best separated');
check(bestKey({...result,mode:'timetrial'})===bestKey({...result,mode:'timetrial',rival}),'inactive rival does not fragment time trials');
let board=recordFinish(createLeaderboard(),result,{id:'test',name:'Test'}).board;board=recordFinish(board,{...result,rival,timeSec:99},{id:'test',name:'Test'}).board;
check(board.entries.length===2,'custom record never replaces default leaderboard record');saveLeaderboard(board);check(loadLeaderboard().entries.length===2,'record separation survives storage roundtrip');
check(createProfile().credits===0,'test fixtures do not alter career defaults');
check(bestKey({...result,rival:normal.state.rival})===bestKey(result),'legacy live rival actor is never mistaken for custom setup');
app.returnToMenu();const raceRival={car:'stuttgart_959s',driverId:'iko_ren',upgradeLevel:2};
app.setRaceSettings({mode:'duel',rival:raceRival,cpuDifficulty:'medium'});app.autopilot=true;app.startCampaign();app._scriptedCrashDone=true;
for(let frame=0;frame<3000&&['countdown','racing','ticket'].includes(app.duel.state.status);frame++)app.advance(.1);
const finish=app.duel.state;
check(finish.status==='stage_result'&&finish.results?.completed,'input-only custom rival race completes both valid laps');
check(finish.rival.car===raceRival.car&&finish.rival.upgrades.engine===2,'chosen rival build survives real race');
check(app.profile.personalBests[bestKey({...finish,laps:finish.lapsTotal,rival:raceRival})]===finish.results.timeSec,'actual custom race settles into correct best class');
check(app.leaderboard.entries.some(row=>row.rival?.car===raceRival.car),'actual App saves custom rival record metadata');
console.log(`Custom rival input-only race: ${finish.results.timeSec.toFixed(2)}s, ${finish.majorCrashes} crashes.`);
console.log(`Playground and custom rivals: ${checks} checks passed.`);
