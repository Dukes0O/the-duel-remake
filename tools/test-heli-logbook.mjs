import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {heliOf, normalizeHeli} from '../src/heli/heli-save.js';
import {recordLogbook, awardLogbook, logbookOf, logbookView, LOGBOOK_PLACES, RANKS} from '../src/heli/heli-logbook.js';
import {wearSkin, gearWorn} from '../src/heli/heli-skins.js';
import {createProfile, saveProfile, loadProfile} from '../src/progression.js';

const on = {enabled: true};
let p = {credits: 1234, heli: {version: 1}};
const original = structuredClone(p);
assert.equal(recordLogbook(p, {flight: 'tremblant-woods'}), p);
assert.equal(awardLogbook(p).profile, p);
assert.equal(awardLogbook(p, on).ranks.length, 0);
assert.equal(logbookOf(p).flights, 0);
assert.deepEqual(p, original);
p.heli.lessons = {liftoff: true, hover: true, landing: true, carry: true};
let result = awardLogbook(p, on); p = result.profile;
assert.deepEqual(result.ranks.map(r => r.id), ['student']);
assert.equal(awardLogbook(p, on).profile, p, 'rank is awarded once');
assert.equal(logbookView(p).books.length, 0);
for (let i = 0; i < 9; i++) p = recordLogbook(p, {...on, flight: 'tremblant-woods'});
assert.equal(awardLogbook(p, on).ranks.length, 0, 'nine flights do not earn Private');
p = recordLogbook(p, {...on, flight: 'tremblant-snow'});
result = awardLogbook(p, on); p = result.profile;
assert.equal(result.ranks[0].id, 'private');
assert.equal(logbookView(p).books[0].year, 1964);
for (const job of ['car', 'crate']) p = recordLogbook(p, {...on, job});
assert.equal(awardLogbook(p, on).ranks.length, 0, 'Commercial needs a fire too');
p = recordLogbook(p, {...on, job: 'fire'});
result = awardLogbook(p, on); p = result.profile;
assert.equal(result.ranks[0].id, 'commercial');
p = recordLogbook(p, {...on, job: 'rescue'});
assert.equal(awardLogbook(p, on).ranks.length, 0);
p = recordLogbook(p, {...on, job: 'ski'});
result = awardLogbook(p, on); p = result.profile;
assert.equal(result.ranks[0].id, 'mountain');
for (const place of LOGBOOK_PLACES) p = recordLogbook(p, {...on, flight: place === 'titan-stadium' ? 'titan-arena' : place});
while (logbookOf(p).flights < 49) p = recordLogbook(p, {...on, flight: 'tremblant-woods'});
assert.equal(awardLogbook(p, on).ranks.length, 0, '49 flights do not earn Chief');
p = recordLogbook(p, {...on, flight: 'tremblant-woods'});
result = awardLogbook(p, on); p = result.profile;
assert.equal(result.ranks[0].id, 'chief');
assert.equal(logbookView(p).books.length, 4);
assert.equal(p.credits, 1234, 'career never moves money');
assert.deepEqual(heliOf(p).skins.owned, RANKS.map(r => r.skin));
for (const rank of RANKS) {
  const worn = wearSkin(p, rank.skin, on);
  assert.equal(worn.ok, true);
  assert.deepEqual(gearWorn(worn.profile, on), [], 'rank paint grants no mission gear');
}
const noTable = structuredClone(p);
noTable.heli.logbook.awarded = 4;
noTable.heli.logbook.visited = noTable.heli.logbook.visited.filter(id => id !== 'the-table');
assert.equal(awardLogbook(noTable, on).ranks.length, 0, 'Chief needs the Table');
const future = {...p.heli, futureHeli: {answer: 42}, logbook: {...p.heli.logbook, futureBook: [7], jobs: {...p.heli.logbook.jobs, futureJob: 9}}};
const normalized = normalizeHeli(future);
assert.deepEqual(normalized.futureHeli, {answer: 42});
assert.deepEqual(normalized.logbook.futureBook, [7]);
assert.equal(normalized.logbook.jobs.futureJob, 9);
assert.deepEqual(normalizeHeli(normalized), normalized);
const data = new Map();
const storage = {getItem: key => data.get(key) ?? null, setItem: (key, value) => data.set(key, value), removeItem: key => data.delete(key)};
assert.ok(saveProfile({...createProfile(), credits: p.credits, heli: normalized}, storage));
assert.deepEqual(loadProfile(storage).heli, normalized, 'all rank paints, counts and future keys survive real save/load');
assert.equal(normalizeHeli({...future, logbook: {flights: -3, awarded: 99, jobs: {car: Infinity}, visited: ['bad', 'the-table', 'the-table']}}).logbook.flights, 0);
const uncloneable = normalizeHeli({...future, logbook: {flights: 12, future: () => {}, jobs: {car: 2, future: () => {}}}});
assert.equal(uncloneable.logbook.flights, 12, 'invalid future data cannot wipe valid counts');
assert.equal(uncloneable.logbook.jobs.car, 2);
assert.equal(uncloneable.logbook.future, undefined);
// A genuine pre-logbook shape: no invented flights/jobs, and all existing fields survive.
const old = JSON.parse(readFileSync(new URL('./fixtures/saves/13-heli-skins.json', import.meta.url)));
const oldHeli = old.storage['the-duel-players-v2'].players[0].profile.heli;
const before = normalizeHeli(oldHeli);
assert.equal(before.logbook, undefined);
assert.equal(logbookOf({heli: before}).flights, 0);
assert.deepEqual(before.skins, oldHeli.skins);
assert.equal(before.flights, 27);
console.log('HELI-LOGBOOK: scripted five-rank career, boundaries, old save and rank paints passed');
